async function injectLocale(filename, translations) {
  const filePath = path.join(LOCALES_DIR, filename)
  try {
    const raw = await fs.readFile(filePath, 'utf-8')
    const json = JSON.parse(raw)
    if (!json.translation) {
      json.translation = {}
    }

    for (const [key, val] of Object.entries(translations)) {
      json.translation[key] = val
    }

    await fs.writeFile(filePath, JSON.stringify(json, null, 2) + '\n', 'utf-8')
    console.log(
      `Successfully injected ${Object.keys(translations).length} keys into ${filename}`
    )
  } catch (err) {
    console.error(`Error injecting into ${filename}:`, err)
  }
}

