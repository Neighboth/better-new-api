const locales = ['en', 'zh', 'zh-TW', 'fr', 'ja', 'ru', 'vi', 'tr']
const readLocale = (locale: string): Record<string, string> =>
  JSON.parse(readFileSync(`src/i18n/locales/${locale}.json`, 'utf8'))
    .translation

describe('statistics and permission translations', () => {
  const english = readLocale('en')
  for (const locale of locales) {
    test(`covers the dashboard and permission catalog in ${locale}`, () => {
      const translations = readLocale(locale)
      for (const key of keys) {
        expect(translations[key], `${locale}: ${key}`).toBeTruthy()
        const sharedTerms =
          (locale === 'tr' && key === 'Model') ||
          (locale === 'fr' && ['Auto', 'Client', 'Clients'].includes(key))
        if (
          locale !== 'en' &&
          !sharedTerms &&
          /[a-zA-Z]{3}/.test(english[key] ?? '')
        ) {
          expect(translations[key], `${locale}: ${key}`).not.toBe(english[key])
        }
      }
    })
  }
})
